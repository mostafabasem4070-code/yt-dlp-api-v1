async def browser_manual_extract() -> Dict[str, Any]:
    """استخراج الكوكيز فورياً يدوياً بطلب من المستخدم، وحفظها وإنهاء الجلسة."""
    global _active_context, _active_page
    if not _active_context:
        return {"success": False, "message": "لا توجد جلسة متصفح نشطة لاستخراج الكوكيز منها."}

    try:
        cookies = await _active_context.cookies()
        if not cookies:
            return {"success": False, "message": "لم يتم العثور على أي كوكيز في المتصفح حتى الآن."}

        if not _is_youtube_authenticated(cookies):
            return {
                "success": False,
                "message": "لم يكتمل تسجيل الدخول لحساب Google بعد (توجد كوكيز زائر فقط). يرجى إتمام تسجيل الدخول أولاً وسيتم حفظ الكوكيز تلقائياً فور الدخول."
            }

        cookies = await _sync_youtube_session_cookies(_active_context, _active_page)
        count = await _save_extracted_cookies(cookies)
        await _cleanup_browser_resources()
        return {
            "success": True,
            "message": f"تم استخراج {count} كوكي مسجلة وحفظها بنجاح في ملف cookies.txt!",
            "cookies_count": count
        }
    except Exception as e:
        logger.error(f"Manual extract error: {e}", exc_info=True)
        return {"success": False, "error": str(e)}


