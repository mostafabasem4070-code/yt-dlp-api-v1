async def capture_browser_screenshot() -> Dict[str, Any]:
    """التقاط لقطة شاشة سريعة من المتصفح النشط كـ Base64 JPEG."""
    global _active_page
    if not _active_page or _active_page.is_closed():
        return {
            "success": False,
            "message": "لا يوجد متصفح نشط حالياً.",
            "status": _auth_session["status"]
        }

    try:
        img_bytes = await _active_page.screenshot(type="jpeg", quality=65)
        b64 = base64.b64encode(img_bytes).decode("ascii")
        url = _active_page.url
        title = await _active_page.title()
        return {
            "success": True,
            "image": f"data:image/jpeg;base64,{b64}",
            "url": url,
            "title": title,
            "status": _auth_session["status"],
            "message": _auth_session.get("message", "")
        }
    except Exception as e:
        return {"success": False, "error": str(e), "status": _auth_session["status"]}


async def browser_mouse_click(x: int, y: int) -> Dict[str, Any]:
    """إرسال نقرة ماوس إلى إحداثيات محددة في صفحة المتصفح."""
    global _active_page
    if not _active_page or _active_page.is_closed():
        return {"success": False, "message": "لا يوجد متصفح نشط."}

    try:
        await _active_page.mouse.click(x, y)
        await asyncio.sleep(0.4)
        return await capture_browser_screenshot()
    except Exception as e:
        return {"success": False, "error": str(e)}


async def browser_keyboard_type(text: str, press_enter: bool = False) -> Dict[str, Any]:
    """كتابة نص في الحقل النشط بالمتصفح، مع خيار الضغط على Enter."""
    global _active_page
    if not _active_page or _active_page.is_closed():
        return {"success": False, "message": "لا يوجد متصفح نشط."}

    try:
        await _active_page.keyboard.type(text, delay=35)
        if press_enter:
            await asyncio.sleep(0.2)
            await _active_page.keyboard.press("Enter")
        await asyncio.sleep(0.5)
        return await capture_browser_screenshot()
    except Exception as e:
        return {"success": False, "error": str(e)}


async def browser_keyboard_key(key: str) -> Dict[str, Any]:
    """الضغط على مفتاح معين (مثل Enter, Backspace, Tab, ArrowDown)."""
