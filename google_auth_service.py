def _cookies_to_netscape(cookies: list) -> str:
    """تحويل كوكيز Playwright إلى صيغة Netscape HTTP Cookie File مع ضمان نطاق .youtube.com."""
    lines = ["# Netscape HTTP Cookie File", "# Generated by Google Auth Service", ""]
    yt_cookie_names = {
        c.get("name", "")
        for c in cookies
        if "youtube.com" in str(c.get("domain", "")).lower()
    }
    shared_auth_names = {
        "SID", "HSID", "SSID", "APISID", "SAPISID",
        "__Secure-1PSID", "__Secure-3PSID",
        "__Secure-1PAPISID", "__Secure-3PAPISID",
        "__Secure-1PSIDTS", "__Secure-3PSIDTS",
        "SIDCC", "__Secure-1PSIDCC", "__Secure-3PSIDCC",
        "LOGIN_INFO", "PREF", "SOCS",
    }

    mirrored_to_yt = set()
    for c in cookies:
        domain = c.get("domain", "")
        domain_flag = "FALSE" if domain and not domain.startswith(".") else "TRUE"
        path = c.get("path", "/")
        secure = "TRUE" if c.get("secure", False) else "FALSE"
        expires = int(c.get("expires", 0))
        if expires < 0:
            expires = 0
        name = c.get("name", "")
        value = c.get("value", "")
        prefix = "#HttpOnly_" if c.get("httpOnly") else ""
        lines.append(f"{prefix}{domain}\t{domain_flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}")

        # إذا كان الكوكي مصادقة على .google.com وغير موجود على .youtube.com ننسخه لـ .youtube.com ليعمل مع yt-dlp
        if (
            name in shared_auth_names
            and name not in yt_cookie_names
            and name not in mirrored_to_yt
            and "google." in domain.lower()
            and value
        ):
            mirrored_to_yt.add(name)
            lines.append(f"{prefix}.youtube.com\tTRUE\t/\t{secure}\t{expires}\t{name}\t{value}")

    return "\n".join(lines) + "\n"


def _is_youtube_authenticated(cookies: list) -> bool:
    """التحقق من وجود كوكيز المصادقة الأساسية لحساب Google/YouTube."""
    auth_cookies = {
        "SID", "SSID", "HSID", "LOGIN_INFO", "SAPISID",
        "__Secure-1PSID", "__Secure-3PSID",
        "__Secure-1PAPISID", "__Secure-3PAPISID",
    }
    found = {c["name"] for c in cookies if c.get("name") in auth_cookies and c.get("value")}
    return len(found) >= 2


def _has_youtube_domain_auth(cookies: list) -> bool:
    """التحقق من اكتمال مزامنة جلسة الحساب على نطاق .youtube.com (وجود LOGIN_INFO + كوكيز مصادقة على يوتيوب)."""
    yt_names = {
        c.get("name", "")
        for c in cookies
        if "youtube.com" in str(c.get("domain", "")).lower() and c.get("value")
    }
    has_login_info = "LOGIN_INFO" in yt_names
    has_sid = bool(yt_names.intersection({"SAPISID", "__Secure-3PAPISID", "__Secure-1PAPISID", "SID", "__Secure-3PSID"}))
    return has_login_info and has_sid


async def _sync_youtube_session_cookies(context, page) -> list:
    """
    بعد تسجيل الدخول في حساب Google، نضمن انتقال المتصفح إلى YouTube
    لتوليد كوكي LOGIN_INFO وربط الجلسة بنطاق .youtube.com، ثم الانتقال إلى
    youtube.com/robots.txt لمنع تدوير الكوكيز أثناء إغلاق المتصفح (وفق توصية yt-dlp الرسمية).
    """
    cookies = await context.cookies()
    if not _has_youtube_domain_auth(cookies):
        _update_session(
            status="extracting",
            message="تم تسجيل الدخول لحساب Google! جاري مزامنة جلسة YouTube وتفعيل LOGIN_INFO..."
        )
        logger.info("Google login detected; syncing session with YouTube to acquire LOGIN_INFO...")
        try:
            if page and not page.is_closed():
                await page.goto(YOUTUBE_SYNC_SIGNIN_URL, wait_until="domcontentloaded", timeout=25000)
                for _ in range(7):
                    await asyncio.sleep(1.0)
                    cookies = await context.cookies()
                    if _has_youtube_domain_auth(cookies):
                        break

                if not _has_youtube_domain_auth(cookies):
                    await page.goto("https://www.youtube.com/?hl=ar", wait_until="domcontentloaded", timeout=20000)
                    await asyncio.sleep(3.0)
                    cookies = await context.cookies()
        except Exception as sync_err:
            logger.warning(f"YouTube session sync navigation warning: {sync_err}")

    # محاولة التقاط VISITOR_DATA من صفحة يوتيوب وتحديثه إذا لزم الأمر
    try:
        if page and not page.is_closed() and "youtube.com" in (page.url or ""):
            # الانتقال إلى robots.txt قبل الإغلاق لمنع تدوير الكوكيز الخلفي في يوتيوب
            await page.goto("https://www.youtube.com/robots.txt", wait_until="domcontentloaded", timeout=10000)
            await asyncio.sleep(0.5)
    except Exception:
        pass

    return await context.cookies()


async def _save_extracted_cookies(cookies: list) -> int:
    """حفظ الكوكيز في ملف cookies.txt و cookies_runtime.txt ومسبح التدوير وتحديث الجلسة."""
    netscape_content = _cookies_to_netscape(cookies)
    saved_count = len(cookies)
    try:
        res = save_cookies_content(netscape_content, label="متصفح Google التفاعلي")
        saved_count = res.get("cookies_count", len(cookies))
    except Exception:
        with open(COOKIES_FILE, "w", encoding="utf-8") as f:
            f.write(netscape_content)
    try:
        with open(RUNTIME_COOKIES_FILE, "w", encoding="utf-8") as f:
            f.write(netscape_content)
    except Exception:
        pass

    auth_cookie_names = sorted({
        c["name"] for c in cookies
        if c.get("name") in {"SID", "SSID", "HSID", "LOGIN_INFO", "SAPISID", "__Secure-1PSID", "__Secure-3PSID", "__Secure-3PAPISID"}
    })
    _update_session(
        status="done",
        finished_at=time.time(),
        cookies_count=saved_count,
        message=f"تم استخراج {saved_count} كوكي مسجلة وحفظها بنجاح! المفاتيح: {', '.join(auth_cookie_names[:5])}",
        error=None,
    )
    logger.info(f"Cookies saved: {saved_count} cookies (auth={auth_cookie_names}) → {COOKIES_FILE}")
    return saved_count


async def start_google_login_session(
    timeout_minutes: int = 15,
    headless: Optional[bool] = None,
    target_url: str = YOUTUBE_LOGIN_URL
) -> Dict[str, Any]:
    """
    بدء جلسة تسجيل الدخول التفاعلية لـ Google.
    - على ويندوز: يفتح متصفح مستمر على سطح المكتب + بث في لوحة التحكم.
    - على لينكس/سيرفر: يستخدم Xvfb لفتح متصفح حقيقي مع ملف تعريف دائم لتجاوز كشف "غير آمن".
    """
    global _auth_session

    async with _auth_lock:
        if _auth_session["status"] in ("running", "waiting_login", "extracting"):
            return {
                "success": False,
                "message": "جلسة تسجيل دخول أخرى جارية بالفعل. يُرجى استخدامها أو إلغاؤها.",
                "session": get_auth_session_status()
            }

        _update_session(
            status="running",
            started_at=time.time(),
            finished_at=None,
            message="جاري تجهيز المتصفح ومضادات كشف البوت...",
            cookies_count=0,
            current_url="",
            page_title="",
            error=None,
        )

    # تشغيل المهمة في الخلفية
    asyncio.create_task(_run_login_session(timeout_minutes, headless, target_url))

    return {
        "success": True,
        "message": "تم بدء جلسة تسجيل الدخول. يمكنك التفاعل مع المتصفح من النافذة الآن.",
        "session": get_auth_session_status()
    }


async def _run_login_session(timeout_minutes: int, headless_override: Optional[bool], target_url: str):
    """المنطق الفعلي لتشغيل متصفح Playwright ومراقبته كما كان يعمل في النسخة الأصلية تماماً."""
    global _active_context, _active_page, _active_pw

    try:
        from playwright.async_api import async_playwright  # type: ignore
    except ImportError:
        _update_session(
            status="error",
            finished_at=time.time(),
            error="مكتبة Playwright غير مثبتة. شغّل: pip install playwright && playwright install chromium",
            message="خطأ: مكتبة Playwright غير متوفرة."
        )
        return

    # التأكد من خادم Xvfb على لينكس
    _ensure_x_server()

    # تحديد وضع التشغيل (Headless أو Headed)
    if headless_override is not None:
        use_headless = headless_override
    else:
        # إذا كنا على لينكس ولا يوجد DISPLAY ولا Xvfb، نضطر لوضع headless لتفادي الانهيار
        if sys.platform.startswith("linux") and not os.environ.get("DISPLAY"):
            use_headless = True
        else:
            use_headless = False

    pw = None
    context = None
    page = None

    try:
        pw = await async_playwright().start()
        _active_pw = pw

        _update_session(message="جاري فتح متصفح التخفي المستمر...")

        # مجلد البروفايل الدائم لتجنب اعتبار الجلسة مؤقتة/بوت من قِبل جوجل
        os.makedirs(BROWSER_PROFILE_DIR, exist_ok=True)

        launch_args = [
            "--no-sandbox",
            "--disable-setuid-sandbox",
            "--disable-blink-features=AutomationControlled",
            "--disable-infobars",
            "--disable-dev-shm-usage",
            "--disable-features=IsolateOrigins,site-per-process",
            "--window-size=1280,800",
            "--lang=ar-EG,ar",
        ]

        # محاولة فتح Chrome الحقيقي أولاً إذا كان مثبتاً، أو Chromium الافتراضي
        # هذا يحل مشكلة Google: "قد يكون هذا المتصفح أو التطبيق غير آمن"
        context = None
        for channel in ("chrome", None):
            try:
                launch_kwargs = {
                    "user_data_dir": BROWSER_PROFILE_DIR,
                    "headless": use_headless,
                    "ignore_default_args": ["--enable-automation"],
                    "args": launch_args,
                    "viewport": {"width": 1280, "height": 800},
                    "locale": "ar-EG",
                }
                if channel:
                    launch_kwargs["channel"] = channel

                context = await pw.chromium.launch_persistent_context(**launch_kwargs)
                logger.info(f"Launched persistent context successfully (channel={channel}, headless={use_headless})")
                break
            except Exception as ch_err:
                logger.info(f"Launch with channel={channel} not available: {ch_err}")
                continue

        if not context:
            # إذا فشل كل شيء، نحاول وضع headless=True مع Chromium
            context = await pw.chromium.launch_persistent_context(
                user_data_dir=BROWSER_PROFILE_DIR,
                headless=True,
                ignore_default_args=["--enable-automation"],
                args=launch_args,
                viewport={"width": 1280, "height": 800},
                locale="ar-EG",
            )

        _active_context = context

        # أخذ الصفحة الأولى أو إنشاء صفحة جديدة
        page = context.pages[0] if context.pages else await context.new_page()
        _active_page = page

        _update_session(
            status="waiting_login",
            message=f"المتصفح جاهز في النافذة التفاعلية. (المهلة: {timeout_minutes} دقيقة)",
            current_url=target_url,
        )

        # تحميل صفحة تسجيل الدخول
        try:
            await page.goto(target_url, wait_until="domcontentloaded", timeout=40000)
        except Exception as nav_e:
            logger.warning(f"Navigation warning: {nav_e}")

        # حلقة فحص دورية لاكتشاف إتمام تسجيل الدخول تلقائياً
        deadline = time.time() + (timeout_minutes * 60)
        authenticated = False

        while time.time() < deadline:
            if _auth_session["status"] in ("idle", "done", "error"):
                return

            await asyncio.sleep(2)

            try:
                if page.is_closed():
                    break

                curr_url = page.url
                curr_title = await page.title()
                _update_session(current_url=curr_url, page_title=curr_title)

                cookies = await context.cookies()
                if _is_youtube_authenticated(cookies):
                    authenticated = True
                    logger.info(f"Authentication detected! Cookies count: {len(cookies)}")
                    break

                remaining = int(deadline - time.time())
                mins, secs = divmod(remaining, 60)
                _update_session(
                    message=f"في انتظار إتمام تسجيل الدخول... (متبقي {mins}:{secs:02d})"
                )

            except Exception as e:
                logger.debug(f"Check loop error: {e}")
                continue

        if _auth_session["status"] == "done":
            return

        if authenticated:
            _update_session(status="extracting", message="تم كشف الجلسة! جاري مزامنة YouTube واستخراج الكوكيز...")
            all_cookies = await _sync_youtube_session_cookies(context, page)
            await _save_extracted_cookies(all_cookies)
        else:
            if _auth_session["status"] not in ("done", "idle"):
                _update_session(
                    status="timeout",
                    finished_at=time.time(),
                    error="انتهت مهلة تسجيل الدخول. يُرجى إعادة المحاولة.",
                    message="انتهت المهلة قبل إتمام تسجيل الدخول."
                )

    except Exception as e:
        logger.error(f"Login session execution error: {e}", exc_info=True)
        _update_session(
            status="error",
            finished_at=time.time(),
            error=str(e),
            message=f"خطأ في جلسة تسجيل الدخول: {str(e)}"
        )
    finally:
        await _cleanup_browser_resources()


async def _cleanup_browser_resources():
    """تنظيف وإغلاق موارد المتصفح بأمان."""
    global _active_context, _active_page, _active_pw
    try:
        if _active_page and not _active_page.is_closed():
            await _active_page.close()
    except Exception:
        pass
    try:
        if _active_context:
            await _active_context.close()
    except Exception:
        pass
    try:
        if _active_pw:
            await _active_pw.stop()
    except Exception:
        pass

    _active_page = None
    _active_context = None
    _active_pw = None


